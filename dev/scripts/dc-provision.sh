#!/usr/bin/env bash
# Provision the dev Samba AD domain controller (runs as root INSIDE omnifile-dc).
#
# Idempotent: the domain is provisioned once (marker file); seed users/groups
# are created only when missing; DNS/hosts are re-asserted on every run.
#
# Secrets: passwords are generated here, written to $STATE/ad.env (root, 0600)
# and never echoed. dev/up.sh copies that file to dev/.secrets/ad.env.
#
# DC_CONTAINER=1: run in a plain container instead (the e2e CI job): no
# systemd, no cloud-init, no hostnamectl; `samba` is started in the
# background directly and the container's resolv.conf is left alone.
set -euo pipefail
CONTAINER="${DC_CONTAINER:-0}"
svc() { [ "$CONTAINER" = 1 ] || systemctl "$@"; }
start_dc() {
  if [ "$CONTAINER" = 1 ]; then
    pgrep -x samba >/dev/null || samba --no-process-group
  else
    systemctl unmask samba-ad-dc >/dev/null 2>&1 || true
    systemctl enable samba-ad-dc >/dev/null 2>&1
    systemctl restart samba-ad-dc
  fi
}

export DEBIAN_FRONTEND=noninteractive

REALM="${AD_REALM:-OMNI.TEST}"
DOMAIN="${AD_DOMAIN:-OMNI}"
DC_SHORT="dc1"
DC_FQDN="${DC_SHORT}.${REALM,,}"
NIS_DOMAIN="${DOMAIN,,}"
STATE=/var/lib/omnifile-dev
ENVFILE="$STATE/ad.env"
MARKER="$STATE/dc-provisioned"
SEEDED="$STATE/dc-seeded"

log() { printf '[dc-provision] %s\n' "$*"; }

[ "$(id -u)" -eq 0 ] || { echo "must run as root" >&2; exit 1; }
install -d -m 0700 "$STATE"

dc_ip() { ip -4 -o addr show scope global | awk '{print $4}' | cut -d/ -f1 | head -n1; }
IP="$(dc_ip)"
[ -n "$IP" ] || { echo "cannot determine DC IP" >&2; exit 1; }

# 1. Packages ------------------------------------------------------------------
if ! dpkg -s samba-ad-dc >/dev/null 2>&1 || ! dpkg -s krb5-user >/dev/null 2>&1; then
  log "installing packages"
  echo "krb5-config krb5-config/default_realm string $REALM" | debconf-set-selections
  echo "krb5-config krb5-config/kerberos_servers string $DC_FQDN" | debconf-set-selections
  echo "krb5-config krb5-config/admin_server string $DC_FQDN" | debconf-set-selections
  apt-get update -qq
  apt-get install -y -qq samba samba-ad-dc winbind krb5-user smbclient ldb-tools \
    dnsutils acl attr openssl iproute2 procps >/dev/null
fi

# 2. Hostname (cloud-init must not rename us back) ----------------------------------
if [ "$CONTAINER" != 1 ]; then
install -d /etc/cloud/cloud.cfg.d
cat >/etc/cloud/cloud.cfg.d/99-omnifile-dev.cfg <<'EOF'
preserve_hostname: true
manage_etc_hosts: false
EOF
hostnamectl set-hostname "$DC_SHORT"
fi
# Rewritten in place (cat >), not with sed -i: in a container /etc/hosts is a
# bind mount that can't be replaced by rename.
hosts="$(sed -e '/ omnifile-dev-dc$/d' -e "/[[:space:]]${DC_SHORT}\$/d" -e "/${DC_FQDN}/d" /etc/hosts)"
printf '%s\n%s %s %s # omnifile-dev-dc\n' "$hosts" "$IP" "$DC_FQDN" "$DC_SHORT" >/etc/hosts

# 3. Domain provision (once) ------------------------------------------------------
if [ ! -f "$MARKER" ]; then
  log "provisioning domain $REALM / $DOMAIN"

  # The AD DC role replaces the file-server daemons.
  svc disable --now smbd nmbd winbind >/dev/null 2>&1 || true
  svc mask smbd nmbd winbind >/dev/null 2>&1 || true

  # Upstream DNS for the Samba forwarder, captured before resolved goes away.
  UPSTREAM=""
  if [ -r /run/systemd/resolve/resolv.conf ]; then
    UPSTREAM="$(awk '/^nameserver/ && $2 !~ /^127\./ {print $2; exit}' /run/systemd/resolve/resolv.conf)"
  fi
  UPSTREAM="${UPSTREAM:-1.1.1.1}"

  gen_pw() { printf 'Dv1-%s' "$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c 24)"; }

  umask 077
  ADMIN_PW="$(gen_pw)"
  {
    echo "# Generated by dc-provision.sh. DEV ONLY. Never commit."
    echo "AD_REALM='$REALM'"
    echo "AD_DOMAIN='$DOMAIN'"
    echo "AD_DC_HOST='$DC_FQDN'"
    echo "AD_ADMIN_USER='Administrator'"
    echo "AD_ADMIN_PASSWORD='$ADMIN_PW'"
  } >"$ENVFILE"

  # Provision wants a plain resolv.conf and no smb.conf.
  if [ "$CONTAINER" != 1 ]; then
    svc disable --now systemd-resolved >/dev/null 2>&1 || true
    rm -f /etc/resolv.conf
    printf 'nameserver %s\n' "$UPSTREAM" >/etc/resolv.conf
  fi
  [ -f /etc/samba/smb.conf ] && mv /etc/samba/smb.conf "/etc/samba/smb.conf.orig.$(date +%s)"

  samba-tool domain provision \
    --use-rfc2307 \
    --realm="$REALM" --domain="$DOMAIN" \
    --server-role=dc --dns-backend=SAMBA_INTERNAL \
    --host-ip="$IP" \
    --adminpass="$ADMIN_PW" >"$STATE/provision.log" 2>&1

  ln -sf /var/lib/samba/private/krb5.conf /etc/krb5.conf
  # Dev convenience: passwords never expire.
  samba-tool domain passwordsettings set --max-pwd-age=0 --min-pwd-age=0 >/dev/null

  start_dc
  touch "$MARKER"
fi

# 4. DNS: the DC resolves through itself (re-asserted every run) -------------------
if [ "$CONTAINER" = 1 ]; then
  # The DC resolves through itself (its own DNS updates need it); written in
  # place, the container's resolv.conf is a bind mount.
  grep -q "^nameserver $IP\$" /etc/resolv.conf \
    || printf 'nameserver %s\nsearch %s\n' "$IP" "${REALM,,}" >/etc/resolv.conf
  start_dc
elif [ "$(readlink -f /etc/resolv.conf)" != "/etc/resolv.conf" ] || ! grep -q "^nameserver $IP\$" /etc/resolv.conf; then
  svc disable --now systemd-resolved >/dev/null 2>&1 || true
  rm -f /etc/resolv.conf
  printf 'nameserver %s\nsearch %s\n' "$IP" "${REALM,,}" >/etc/resolv.conf
fi
[ "$CONTAINER" = 1 ] || systemctl is-active --quiet samba-ad-dc || systemctl restart samba-ad-dc

# Wait for AD to answer.
for i in $(seq 1 60); do
  if samba-tool domain level show >/dev/null 2>&1; then break; fi
  sleep 2
  [ "$i" -lt 60 ] || { echo "samba AD did not become ready" >&2; exit 1; }
done

# If the DC IP ever changed (DHCP), refresh its DNS records.
samba_dnsupdate --use-samba-tool >/dev/null 2>&1 || true

# 5. Seed data (once) -----------------------------------------------------------------
if [ ! -f "$SEEDED" ]; then
  log "seeding users and groups"
  # shellcheck disable=SC1090
  . "$ENVFILE"
  umask 077

  gen_pw() { printf 'Dv1-%s' "$(openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c 24)"; }

  # Domain Users is every user's primary group, so it needs a gidNumber too.
  samba-tool group addunixattrs "Domain Users" 10000 >/dev/null 2>&1 || true

  # name  uidNumber  (password var is AD_PASSWORD_<UPPER, - -> _>)
  users="geo-reader:20001 geo-writer:20002 geo-none:20003 omni-admin:20004 geo-owner:20005 geo-nested:20006"
  # name  gidNumber
  groups="Proj-Readers:30001 Proj-Writers:30002 Proj-Owners:30003 OmniFile-Admins:30004 Proj-Readers-Nested:30005"

  for g in $groups; do
    name="${g%%:*}"; gid="${g##*:}"
    if ! samba-tool group show "$name" >/dev/null 2>&1; then
      samba-tool group add "$name" --gid-number="$gid" --nis-domain="$NIS_DOMAIN" >/dev/null
    fi
  done

  for u in $users; do
    name="${u%%:*}"; uid="${u##*:}"
    var="AD_PASSWORD_$(printf '%s' "$name" | tr 'a-z-' 'A-Z_')"
    pw="$(gen_pw)"
    if ! samba-tool user show "$name" >/dev/null 2>&1; then
      samba-tool user create "$name" "$pw" \
        --uid-number="$uid" --gid-number=10000 \
        --login-shell=/bin/bash --unix-home="/home/$name" \
        --nis-domain="$NIS_DOMAIN" \
        --given-name="${name%%-*}" --surname="${name#*-}" >/dev/null
      printf "%s='%s'\n" "$var" "$pw" >>"$ENVFILE"
    fi
  done

  # Memberships (permission-matrix users, plus the nested-group case).
  samba-tool group addmembers Proj-Readers geo-reader >/dev/null
  samba-tool group addmembers Proj-Writers geo-writer >/dev/null
  samba-tool group addmembers Proj-Owners geo-owner >/dev/null
  samba-tool group addmembers OmniFile-Admins omni-admin >/dev/null
  # Nested: geo-nested -> Proj-Readers-Nested -> Proj-Readers
  samba-tool group addmembers Proj-Readers-Nested geo-nested >/dev/null
  samba-tool group addmembers Proj-Readers Proj-Readers-Nested >/dev/null
  # geo-none stays in Domain Users only.

  chmod 0600 "$ENVFILE"
  touch "$SEEDED"
fi

# Publish the DC address for the edge VM (dev/up.sh copies this file out).
sed -i '/^AD_DC_IP=/d' "$ENVFILE"
printf "AD_DC_IP='%s'\n" "$IP" >>"$ENVFILE"
chmod 0600 "$ENVFILE"

# 6. Self-check (no secrets printed) -----------------------------------------------------
host -t SRV "_ldap._tcp.${REALM,,}" "$IP" >/dev/null
log "ready: realm=$REALM dc=$DC_FQDN ip=$IP"
